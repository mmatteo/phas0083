ref = dict(color=col.ref, ls="--")  # style of exact curves
thr = dict(color=col.thr, ls=":")   # style of thresholds


def shades(color, n):
    """n shades of a colour: dark, itself, light."""
    rgb = np.array(to_rgb(color))
    dark, light = 0.35 * rgb, rgb + (1 - rgb) * 0.55
    result = []
    for t in np.linspace(0, 1, n):
        a, b, u = (dark, rgb, 2 * t) if t < 0.5 else \
            (rgb, light, 2 * t - 1)
        result.append(a + (b - a) * u)
    return result


# ------------------------------------------------------------

nu = 2000
x_obs = 2100
x = np.arange(1900, 2200)

fig, ax = plt.subplots()
ax.plot(x, poisson.sf(x, nu), color=col.cdf,
        label="$1-F(x)$ under $H_0$")
ax.axvline(x_obs, color=col.data,
           label=r"$x_\mathrm{obs}$")
ax.set_xlabel("$x$ (number of counts)")
ax.set_ylabel("$1-F(x)$")
ax.legend()

plt.show()
